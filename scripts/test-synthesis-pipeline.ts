function displayAnalysisResults(analysis: AnalysisResult): void {
  console.log('\n📊 ANALYSIS RESULTS')
  console.log('─'.repeat(60))
  
  // Patterns
  console.log(`\n🔍 Patterns (${analysis.patterns.length}):`)
  analysis.patterns.forEach((p, i) => {
    console.log(`\n   ${i + 1}. ${p.claim}`)
    console.log(`      Support: ${p.support.count}/${p.support.total} papers (${Math.round(p.support.count / p.support.total * 100)}%)`)
    console.log(`      Confidence: ${(p.confidence * 100).toFixed(0)}%`)
    console.log(`      Consistency: ${p.consistency}`)
  })
  
  // Contradictions
  console.log(`\n⚡ Contradictions (${analysis.contradictions.length}):`)
  analysis.contradictions.forEach((c, i) => {
    console.log(`\n   ${i + 1}. ${c.description}`)
    c.sides.forEach((side, j) => {
      console.log(`      Side ${j + 1}: ${side.position} (${side.papers.length} papers)`)
    })
    if (c.possibleExplanation) {
      console.log(`      Possible explanation: ${c.possibleExplanation}`)
    }
  })
  
  // Gaps
  console.log(`\n🕳️  Gaps (${analysis.gaps.length}):`)
  analysis.gaps.forEach((g, i) => {
    console.log(`\n   ${i + 1}. ${g.description}`)
    console.log(`      Type: ${g.type}`)
    console.log(`      Relevance: ${g.relevance}`)
    console.log(`      Confidence: ${(g.confidence * 100).toFixed(0)}%`)
  })
  
  // Key Insights
  if (analysis.keyInsights.length > 0) {
    console.log(`\n💡 Key Insights:`)
    analysis.keyInsights.forEach((insight, i) => {
      console.log(`   ${i + 1}. ${insight}`)
    })
  }
}

