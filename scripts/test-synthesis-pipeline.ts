/**
 * Create outline sections from profile for plan alignment
 */
function createOutlineSectionsFromProfile(
  profile: PaperProfile,
  paperType: PaperTypeKey,
  targetWordCount: number
): OutlineSectionInput[] {
  const sections = profile.structure.appropriateSections
  const totalMinWords = sections.reduce((sum, s) => sum + s.minWords, 0)
  
  return annotateOutlineSections(
    sections.map(section => ({
      sectionKey: section.key,
      title: section.title,
      expectedWords: Math.round((section.minWords / totalMinWords) * targetWordCount),
      keyPoints: section.keyElements
    })),
    paperType
  )
}

